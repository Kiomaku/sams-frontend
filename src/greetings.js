let last = "";
export function pickGreeting(date = new Date()) {
  const h = date.getHours();
  const pool = h < 5 ? G.late : h < 12 ? G.morning : h < 17 ? G.afternoon : h < 21 ? G.evening : G.night;
  let g;
  do { g = pool[Math.floor(Math.random() * pool.length)]; } while (g[0] === last && pool.length > 1);
  last = g[0];
  return g;
}
